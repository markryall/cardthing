//! A committed markdown snapshot of the board, so someone browsing the repo on
//! GitHub (or any forge) can see where things are at without cloning it.
//!
//! Opt-in: written only when `.cards.toml` sets `snapshot = "<path>"`. It is
//! rebuilt from the full card list after every card write, never patched, and
//! deterministic (no timestamps), so it only changes when the board does.

use crate::dependencies;
use crate::models::{Card, Config};
use crate::storage;
use anyhow::{Context, Result};
use std::fs;
use std::path::{Component, Path, PathBuf};

const HEADER: &str = "<!-- Generated by cardthing from .cards/*.toml. Don't edit by hand: \
run `cardthing snapshot` to regenerate. -->";

/// Rewrite the snapshot if the config asks for one. Returns the path written,
/// or `None` when no snapshot is configured.
pub fn refresh() -> Result<Option<PathBuf>> {
    let config = Config::load();
    let Some(path) = config.snapshot.as_deref() else {
        return Ok(None);
    };
    let path = PathBuf::from(path);
    let cards = storage::list_cards()?;
    write_atomically(&path, &render(&cards, &config, &path))?;
    Ok(Some(path))
}

/// [`refresh`] for callers whose own write already succeeded: a failure to
/// update the snapshot is reported but doesn't fail the card write.
pub fn refresh_quietly() {
    if let Err(e) = refresh() {
        eprintln!("Warning: failed to update board snapshot: {:#}", e);
    }
}

/// Write via a temp file and rename, so concurrent writers never leave a
/// half-written snapshot behind.
fn write_atomically(path: &Path, content: &str) -> Result<()> {
    if let Some(dir) = path.parent().filter(|d| !d.as_os_str().is_empty()) {
        fs::create_dir_all(dir)?;
    }
    let file_name = path
        .file_name()
        .and_then(|n| n.to_str())
        .context("Snapshot path has no file name")?;
    let tmp = path.with_file_name(format!(".{}.{}.tmp", file_name, std::process::id()));
    fs::write(&tmp, content).context(format!("Failed to write {}", tmp.display()))?;
    fs::rename(&tmp, path).context(format!("Failed to write {}", path.display()))?;
    Ok(())
}

/// Render the board as markdown: one section per status in config order (then
/// any statuses the config doesn't know), cards in board order.
pub fn render(cards: &[Card], config: &Config, snapshot_path: &Path) -> String {
    let link_prefix = link_prefix(snapshot_path);
    let mut out = format!("{}\n\n# {}\n", HEADER, escape(&config.title));

    let mut sections: Vec<(String, String)> = config
        .statuses
        .iter()
        .map(|s| (s.id.clone(), s.label.clone()))
        .collect();
    let mut unknown: Vec<String> = cards
        .iter()
        .map(|c| c.status.clone())
        .filter(|id| !sections.iter().any(|(known, _)| known == id))
        .collect();
    unknown.sort();
    unknown.dedup();
    sections.extend(unknown.into_iter().map(|id| (id.clone(), id)));

    for (id, label) in sections {
        let mut column: Vec<&Card> = cards.iter().filter(|c| c.status == id).collect();
        column.sort_by(|a, b| {
            let ao = a.order.unwrap_or(u32::MAX);
            let bo = b.order.unwrap_or(u32::MAX);
            ao.cmp(&bo)
                .then_with(|| a.created_at.cmp(&b.created_at))
                .then_with(|| a.name.cmp(&b.name))
        });

        out.push_str(&format!("\n## {} ({})\n\n", escape(&label), column.len()));
        if column.is_empty() {
            out.push_str("_none_\n");
        }
        for card in column {
            out.push_str(&render_card(card, cards, &link_prefix));
        }
    }
    out
}

fn render_card(card: &Card, cards: &[Card], link_prefix: &str) -> String {
    let mut parts = Vec::new();
    if let Some(owner) = &card.owner {
        parts.push(format!("owner: {}", escape(owner)));
    }
    if let Some(priority) = &card.priority {
        parts.push(format!("priority: {}", escape(priority)));
    }
    if let Some(due) = card.due_at {
        parts.push(format!("due: {}", due.format("%Y-%m-%d")));
    }
    if !card.tags.is_empty() {
        let tags: Vec<String> = card.tags.iter().map(|t| format!("`{}`", t)).collect();
        parts.push(format!("tags: {}", tags.join(", ")));
    }
    if !card.checklist.is_empty() {
        let checked = card.checklist.iter().filter(|i| i.checked).count();
        parts.push(format!("checklist: {}/{}", checked, card.checklist.len()));
    }
    if card.needs_human {
        parts.push("needs a human".to_string());
    }
    let blockers = dependencies::open_blockers(card, cards);
    if !blockers.is_empty() {
        let names: Vec<String> = blockers.iter().map(|b| escape(b)).collect();
        parts.push(format!("🔒 blocked by: {}", names.join(", ")));
    }

    let mut line = format!(
        "- [{}]({}{}.toml)",
        escape(&card.name),
        link_prefix,
        storage::sanitize_filename(&card.name)
    );
    if !parts.is_empty() {
        line.push_str(" — ");
        line.push_str(&parts.join(" · "));
    }
    line.push('\n');
    line
}

/// The relative path from the snapshot's directory to the cards directory, so
/// links work when the file is viewed on a forge.
fn link_prefix(snapshot_path: &Path) -> String {
    let dir: Vec<Component> = snapshot_path
        .parent()
        .map(|p| {
            p.components()
                .filter(|c| !matches!(c, Component::CurDir))
                .collect()
        })
        .unwrap_or_default();
    let cards_dir = storage::get_cards_path();
    if dir.len() == 1 && Path::new(dir[0].as_os_str()) == cards_dir {
        return String::new();
    }
    format!("{}{}/", "../".repeat(dir.len()), cards_dir.display())
}

/// Escape the characters that would otherwise turn a card name into markdown.
fn escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        if matches!(
            c,
            '\\' | '[' | ']' | '*' | '_' | '`' | '<' | '>' | '#' | '|'
        ) {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::models::ChecklistItem;
    use chrono::{TimeZone, Utc};

    fn card(name: &str, status: &str, minute: u32) -> Card {
        let mut c = Card::new(name.to_string(), String::new());
        c.status = status.to_string();
        c.created_at = Utc.with_ymd_and_hms(2026, 1, 1, 0, minute, 0).unwrap();
        c.updated_at = c.created_at;
        c
    }

    fn config() -> Config {
        Config {
            title: "My Board".to_string(),
            ..Default::default()
        }
    }

    #[test]
    fn renders_sections_in_config_order_with_counts() {
        let cards = vec![card("b", "done", 1), card("a", "todo", 2)];
        let out = render(&cards, &config(), Path::new(".cards/README.md"));
        assert!(out.starts_with("<!-- Generated by cardthing"));
        assert!(out.contains("# My Board\n"));
        let todo = out.find("## Todo (1)").unwrap();
        let progress = out.find("## In Progress (0)\n\n_none_\n").unwrap();
        let done = out.find("## Done (1)").unwrap();
        assert!(todo < progress && progress < done);
    }

    #[test]
    fn orders_cards_like_the_board() {
        let mut first = card("first", "todo", 5);
        first.order = Some(0);
        let cards = vec![card("older", "todo", 1), card("newer", "todo", 2), first];
        let out = render(&cards, &config(), Path::new(".cards/README.md"));
        let pos = |n: &str| out.find(&format!("[{}]", n)).unwrap();
        assert!(pos("first") < pos("older"));
        assert!(pos("older") < pos("newer"));
    }

    #[test]
    fn lists_fields_and_open_blockers() {
        let mut a = card("Ship It", "todo", 1);
        a.owner = Some("mark".to_string());
        a.priority = Some("high".to_string());
        a.due_at = Some(Utc.with_ymd_and_hms(2026, 11, 5, 0, 0, 0).unwrap());
        a.tags = vec!["x".to_string(), "y".to_string()];
        a.checklist = vec![
            ChecklistItem {
                text: "one".to_string(),
                checked: true,
            },
            ChecklistItem {
                text: "two".to_string(),
                checked: false,
            },
        ];
        a.blocked_by = vec!["Design".to_string(), "Spike".to_string()];
        let design = card("Design", "todo", 2);
        let spike = card("Spike", "done", 3);
        let out = render(
            &[a, design, spike],
            &config(),
            Path::new(".cards/README.md"),
        );
        assert!(out.contains(
            "- [Ship It](ship-it.toml) — owner: mark · priority: high · due: 2026-11-05 \
             · tags: `x`, `y` · checklist: 1/2 · 🔒 blocked by: Design\n"
        ));
        assert!(out.contains("- [Spike](spike.toml)\n"));
    }

    #[test]
    fn keeps_cards_with_unknown_statuses() {
        let out = render(
            &[card("lost", "limbo", 1)],
            &config(),
            Path::new("CARDS.md"),
        );
        assert!(out.contains("## limbo (1)\n\n- [lost](.cards/lost.toml)\n"));
    }

    #[test]
    fn links_are_relative_to_the_snapshot() {
        assert_eq!(link_prefix(Path::new(".cards/README.md")), "");
        assert_eq!(link_prefix(Path::new("./.cards/README.md")), "");
        assert_eq!(link_prefix(Path::new("CARDS.md")), ".cards/");
        assert_eq!(link_prefix(Path::new("docs/BOARD.md")), "../.cards/");
    }

    #[test]
    fn escapes_markdown_in_names() {
        let out = render(
            &[card("a [b]_c*", "todo", 1)],
            &config(),
            Path::new("CARDS.md"),
        );
        assert!(out.contains("- [a \\[b\\]\\_c\\*](.cards/a-_b__c_.toml)\n"));
    }

    #[test]
    fn is_deterministic() {
        let cards = vec![card("a", "todo", 1), card("b", "todo", 1)];
        let path = Path::new(".cards/README.md");
        assert_eq!(
            render(&cards, &config(), path),
            render(&cards, &config(), path)
        );
    }
}
